import {DRIVERS,safeTargetCandidates} from './learned-targets.mjs';
// Public diagnostic schema only. Never forward arbitrary driver exception data,
// raw values, URLs, selectors, source facts or model-provided additional keys.
// One exception: driver_target_gap carries row-relative structural selectors
// the driver itself generated (see learned-targets.mjs).
const phases=new Set(['after_option_click','after_blur','independent_verify','candidate_resolution','restored_control_failure']);
const keys=['phase','expectedValueHash','observedValueHash','valueMatches','readbackAvailable'];
const countKeys=['candidateCount','exactCandidateCount','visibleTargetCount'];
const sha256=value=>typeof value==='string'&&/^[a-f0-9]{64}$/.test(value);
const entryKeys=['phase','stage','check','selectorMatches','expectedValueHash','observedValueHash','valueMatches','readbackAvailable','normalizedMatch','prefixMatched'];
const entryChecks=new Set(['selector_count','prefix','title','role_identity']);
// A driver that cannot find its click target reports the row's clickable
// candidates: tag, role, public classes and a row-relative structural selector
// only (generated by the driver, build-hash classes removed, no text).
function targetGapDetails(value){
 const own=Reflect.ownKeys(value);if(own.length!==3||own.some(k=>!['phase','driver','candidates'].includes(k)))return null;
 if(!DRIVERS.has(value.driver)||!Array.isArray(value.candidates))return null;
 const candidates=safeTargetCandidates(value.candidates);if(candidates.length!==Math.min(value.candidates.length,12))return null;
 return {phase:'driver_target_gap',driver:value.driver,candidates};
}
// Entry role identity failures: which check failed, on which page, how many
// nodes matched, and hashes only — never the raw title, URL or selector.
function entryDetails(value){
 const own=Reflect.ownKeys(value);if(own.length!==entryKeys.length||own.some(k=>!entryKeys.includes(k)))return null;
 const v=Object.fromEntries(entryKeys.map(k=>[k,Object.getOwnPropertyDescriptor(value,k)?.value]));
 if(!['detail','form'].includes(v.stage)||!entryChecks.has(v.check)||!Number.isInteger(v.selectorMatches)||v.selectorMatches<0||v.selectorMatches>1000)return null;
 if(!sha256(v.expectedValueHash)||typeof v.valueMatches!=='boolean'||typeof v.readbackAvailable!=='boolean')return null;
 if(v.readbackAvailable?!sha256(v.observedValueHash):v.observedValueHash!==null)return null;
 for(const k of ['normalizedMatch','prefixMatched'])if(v[k]!==null&&typeof v[k]!=='boolean')return null;
 return v;
}
export function safeControlErrorDetails(value){
 try{
 if(value&&typeof value==='object'&&!Array.isArray(value)&&[Object.prototype,null].includes(Object.getPrototypeOf(value))&&Object.getOwnPropertyDescriptor(value,'phase')?.value==='entry_role_identity')return entryDetails(value);
 if(value&&typeof value==='object'&&!Array.isArray(value)&&[Object.prototype,null].includes(Object.getPrototypeOf(value))&&Object.getOwnPropertyDescriptor(value,'phase')?.value==='driver_target_gap')return targetGapDetails(value);
 if(!value||typeof value!=='object'||Array.isArray(value)||![Object.prototype,null].includes(Object.getPrototypeOf(value)))return null;
 const descriptors=Object.getOwnPropertyDescriptors(value),phase=descriptors.phase?.value;if(!phases.has(phase))return null;
 const restored=['originalValueHash','unchangedFromBefore','popupClosed','stableReadback','pageUnchanged'];
 const allowed=phase==='candidate_resolution'?[...keys,...countKeys]:phase==='restored_control_failure'?[...keys,...restored]:keys;
 const own=Reflect.ownKeys(value);if(own.length!==allowed.length||own.some(key=>!allowed.includes(key)))return null;
 if(allowed.some(key=>!Object.hasOwn(descriptors,key)||!Object.hasOwn(descriptors[key],'value')))return null;
 const read=key=>descriptors[key].value;
 if(!phases.has(read('phase'))||!sha256(read('expectedValueHash'))||typeof read('valueMatches')!=='boolean'||typeof read('readbackAvailable')!=='boolean')return null;
 if(read('readbackAvailable')?!sha256(read('observedValueHash')):read('observedValueHash')!==null)return null;
 if(phase==='candidate_resolution'&&countKeys.some(key=>!Number.isInteger(read(key))||read(key)<0||read(key)>1000))return null;
 if(phase==='restored_control_failure'&&(!sha256(read('originalValueHash'))||restored.slice(1).some(key=>typeof read(key)!=='boolean')))return null;
 return Object.fromEntries(allowed.map(key=>[key,read(key)]));
 }catch{return null;}
}
